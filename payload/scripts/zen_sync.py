#!/usr/bin/env python3
"""Install and update the "Ambxst" Zen mod from Ambxst's pywalzen.css.

Profiles are the ones Zen itself starts with: the [Install...] Default entry of
each profiles.ini, or explicit paths given with --profile.

Zen has no file watcher for mods. It rebuilds zen-themes.css from each mod's
chrome.css when its mods change, and every new window reloads zen-themes.css as
it stands, so both files are written. A running Zen picks the colours up at once
through the optional watcher (payload/zen/install.sh) or, with --live, through
a window opened and closed for that purpose.
"""

import argparse
import configparser
import json
import os
import re
import shutil
import subprocess
import sys
import tempfile
import time

MOD_ID = "ambxst"
MOD_ENTRY = {
    "id": MOD_ID,
    "name": "Ambxst",
    "description": "Colours from your Ambxst theme, kept in sync by the Zen Browser Sync mod for Ambxst",
    "author": "Ambxst",
    "version": "1.0.0",
    "preferences": False,
}
SHEET_HEADER = "/* Zen Mods - Generated by ZenMods.\n*/\n"
SHEET_FOOTER = "/* End of Zen Mods */\n"
OPEN_TIMEOUT = 8
RELOAD_DELAY = 1.5


def expand(path):
    return os.path.abspath(os.path.expanduser(path))


def zen_roots():
    config = os.environ.get("XDG_CONFIG_HOME") or expand("~/.config")
    return (
        os.path.join(config, "zen"),
        expand("~/.zen"),
        expand("~/.var/app/app.zen_browser.zen/.zen"),
        expand("~/.var/app/app.zen_browser.zen/config/zen"),
    )


def default_profiles(root):
    """Profiles Zen opens by default: one per install, else the Default=1 one."""
    ini = configparser.ConfigParser(interpolation=None)
    ini.optionxform = str
    if not ini.read(os.path.join(root, "profiles.ini"), encoding="utf-8"):
        return []

    def resolve(path, relative="1"):
        return os.path.join(root, path) if relative == "1" else path

    by_path = {
        section["Path"]: resolve(section["Path"], section.get("IsRelative", "1"))
        for name, section in ini.items()
        if name.startswith("Profile") and "Path" in section
    }
    found = [resolve(section["Default"]) for name, section in ini.items()
             if name.startswith("Install") and "Default" in section]
    if not found:
        found = [by_path[section["Path"]] for name, section in ini.items()
                 if name.startswith("Profile") and section.get("Default") == "1" and "Path" in section]
    return [path for path in found if os.path.isdir(path)]


def profile_dirs(explicit):
    if explicit:
        return [expand(path) for path in explicit if os.path.isdir(expand(path))]
    profiles = []
    for root in zen_roots():
        for path in default_profiles(root):
            if path not in profiles:
                profiles.append(path)
    return profiles


def read(path):
    try:
        with open(path, encoding="utf-8") as handle:
            return handle.read()
    except FileNotFoundError:
        return None


def write_atomic(path, content):
    fd, tmp = tempfile.mkstemp(dir=os.path.dirname(path), prefix=".ambxst-zen-")
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as handle:
            handle.write(content)
        os.chmod(tmp, 0o644)
        os.replace(tmp, path)
    except BaseException:
        os.unlink(tmp)
        raise


def register_mod(profile):
    """Add the mod to zen-themes.json. Returns False when the user disabled it in Zen."""
    path = os.path.join(profile, "zen-themes.json")
    try:
        mods = json.loads(read(path) or "{}")
    except json.JSONDecodeError:
        mods = {}
    if not isinstance(mods, dict):
        mods = {}

    current = mods.get(MOD_ID) or {}
    if current.get("enabled") is False:
        return False

    entry = {**MOD_ENTRY, "enabled": True}
    if current != entry:
        mods[MOD_ID] = entry
        write_atomic(path, json.dumps(mods))
    return True


def block(css):
    return (
        f"\n/* Name: {MOD_ENTRY['name']} */\n"
        f"/* Description: {MOD_ENTRY['description']} */\n"
        f"/* Author: @{MOD_ENTRY['author']} */\n"
        + css.rstrip("\n") + "\n\n"
    )


def splice(stylesheet, css):
    """Put the mod's block in zen-themes.css, leaving other mods alone."""
    if stylesheet is None or SHEET_FOOTER.strip() not in stylesheet:
        stylesheet = SHEET_HEADER + SHEET_FOOTER
    pattern = re.compile(
        r"\n?/\* Name: " + re.escape(MOD_ENTRY["name"]) + r" \*/\n.*?\s*"
        r"(?=/\* Name: |/\* End of Zen Mods \*/)",
        re.DOTALL,
    )
    if pattern.search(stylesheet):
        return pattern.sub(lambda _: block(css), stylesheet, 1)
    footer = stylesheet.rindex(SHEET_FOOTER.strip())
    return stylesheet[:footer].rstrip("\n") + "\n" + block(css) + stylesheet[footer:]


def sync_profile(profile, css):
    chrome = os.path.join(profile, "chrome")
    mod_dir = os.path.join(chrome, "zen-themes", MOD_ID)
    os.makedirs(mod_dir, exist_ok=True)
    if not register_mod(profile):
        return False

    changed = False
    mod_css = os.path.join(mod_dir, "chrome.css")
    if read(mod_css) != css:
        write_atomic(mod_css, css)
        changed = True

    sheet_path = os.path.join(chrome, "zen-themes.css")
    sheet = read(sheet_path)
    updated = splice(sheet, css)
    if updated != sheet:
        write_atomic(sheet_path, updated)
        changed = True
    return changed


def windows():
    listed = subprocess.run(["axctl", "window", "list"], capture_output=True, text=True, check=True)
    return json.loads(listed.stdout)


def zen_windows(listed):
    return {window["id"] for window in listed if window.get("app_id") == "zen"}


def watcher_installed():
    """payload/zen/install.sh makes Zen reload by itself when chrome.css changes."""
    found = subprocess.run(["pgrep", "-o", "-x", "zen-bin"], capture_output=True, text=True)
    if found.returncode != 0:
        return False
    try:
        zen_dir = os.path.dirname(os.readlink(f"/proc/{found.stdout.strip()}/exe"))
    except OSError:
        return False
    return os.path.exists(os.path.join(zen_dir, "ambxst-zen-sync.cfg"))


def reload_running_zen():
    """Open a Zen window for a moment: each new window reloads the mods for all."""
    if watcher_installed():
        return

    binary = shutil.which("zen-browser") or shutil.which("zen")
    listed = windows()
    existing = zen_windows(listed)
    focused = next((window for window in listed if window.get("is_focused")), None)
    # Without a window Zen would start or show one for nothing; fullscreen must
    # not be interrupted. The colours arrive with the next window either way.
    if not binary or not existing or (focused and focused.get("is_fullscreen")):
        return

    subprocess.Popen(
        [binary, "--new-window", "about:blank"],
        stdout=subprocess.DEVNULL,
        stderr=subprocess.DEVNULL,
        start_new_session=True,
    )

    opened = set()
    deadline = time.monotonic() + OPEN_TIMEOUT
    while not opened and time.monotonic() < deadline:
        time.sleep(0.1)
        opened = zen_windows(windows()) - existing

    time.sleep(RELOAD_DELAY)
    for window in opened:
        subprocess.run(["axctl", "window", "close", window], capture_output=True)
    if focused:
        subprocess.run(["axctl", "window", "focus", focused["id"]], capture_output=True)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--css", default=expand("~/.cache/ambxst/pywalzen.css"))
    parser.add_argument("--profile", action="append", default=[],
                        help="Zen profile folder; repeatable. Default: the profiles Zen starts with")
    parser.add_argument("--live", action="store_true")
    args = parser.parse_args()

    css = read(args.css)
    if not css or not css.strip():
        print(f"zen_sync: nothing to apply from {args.css}", file=sys.stderr)
        return 1

    profiles = profile_dirs(args.profile)
    if not profiles:
        print("zen_sync: no Zen profile found", file=sys.stderr)
        return 1

    changed = [profile for profile in profiles if sync_profile(profile, css)]
    for profile in changed:
        print(f"zen_sync: updated {profile}")
    if changed and args.live:
        reload_running_zen()
    return 0


if __name__ == "__main__":
    sys.exit(main())
